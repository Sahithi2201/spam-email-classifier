# Import required libraries

import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB
from sklearn.pipeline import Pipeline
from sklearn.metrics import accuracy_score, classification_report

print("All libraries imported successfully!")

#  Create a sample dataset

data = {
    "message": [
        "Congratulations! You won a free prize. Click now",
        "Claim your cash reward today",
        "URGENT! You have won a lottery",
        "Get a free phone by clicking this link",
        "Limited offer! Buy now and save money",
        "You have been selected for a free gift",
        "Earn money fast from home",
        "Winner! Claim your reward immediately",
        "Can we meet for lunch tomorrow?",
        "Please send me the class notes",
        "The meeting starts at 10 AM",
        "I will call you when I reach home",
        "Your appointment is confirmed for Monday",
        "Don't forget to submit the assignment",
        "Are you coming to college today?",
        "Thanks for helping me with the project"
    ],
    "label": [
        "spam", "spam", "spam", "spam",
        "spam", "spam", "spam", "spam",
        "ham", "ham", "ham", "ham",
        "ham", "ham", "ham", "ham"
    ]
}

df = pd.DataFrame(data)

print("Dataset created successfully!")
print("\nFirst five messages:")
print(df.head())

print("\nNumber of messages in each category:")
print(df["label"].value_counts())

#  Train the Spam Email Classifier

# Separate messages and their labels
X = df["message"]
y = df["label"]

# Split data into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.25,
    random_state=42,
    stratify=y
)

# Create the machine learning pipeline
model = Pipeline([
    ("tfidf", TfidfVectorizer()),
    ("classifier", MultinomialNB())
])

# Train the model
model.fit(X_train, y_train)

print("AI model trained successfully!")
print("Training messages:", len(X_train))
print("Testing messages:", len(X_test))

#  Evaluate model performance

y_pred = model.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)

print("MODEL EVALUATION RESULTS")
print("------------------------")
print(f"Accuracy: {accuracy:.2%}")

print("\nClassification Report:")
print(classification_report(
    y_test,
    y_pred,
    zero_division=0
))

print("\nActual vs Predicted:")
for message, actual, predicted in zip(X_test, y_test, y_pred):
    print("Message:", message)
    print("Actual:", actual)
    print("Predicted:", predicted)
    print()

#  Test custom messages

def check_message(message):
    prediction = model.predict([message])[0]

    if prediction == "spam":
        print("Prediction: SPAM 🚨")
    else:
        print("Prediction: NOT SPAM ✅")

    print("Message:", message)


# Try sample messages
check_message("Congratulations! You won a free prize. Click now")

print()

check_message("Can we meet for lunch tomorrow?")

